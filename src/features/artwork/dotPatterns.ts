/**
 * 기본 앨범아트의 도트 패턴 (M12, ADR 0032).
 *
 * 마스코트 패턴 파일을 이은 자리다. 렌더링과 분리해 둔다 (`DotMatrix.vue` 는 패턴을 모른다).
 * 오리지널 도형이며 외부 캐릭터 IP · 이미지 · 이모지를 쓰지 않는다.
 */

/**
 * 행 문자열의 배열. `'1'` 이 켜진 도트, `'0'` 이 꺼진 도트다.
 *
 * 문자열로 두는 이유: 소스에서 패턴 모양이 눈으로 보인다.
 */
export type DotPattern = readonly string[]

/**
 * 카세트 테이프 — 16×12. Kawaii Synth Cassette 의 기본 앨범아트.
 *
 * ```
 * ................
 * .##############.
 * .#............#.
 * .#.##########.#.
 * .#.#.##..##.#.#.
 * .#.#.##..##.#.#.
 * .#.##########.#.
 * .#............#.
 * .#...######...#.
 * .#..#......#..#.
 * .##############.
 * ................
 * ```
 */
export const CASSETTE_DOTS: DotPattern = [
  '0000000000000000',
  '0111111111111110',
  '0100000000000010',
  '0101111111111010',
  '0101011001101010',
  '0101011001101010',
  '0101111111111010',
  '0100000000000010',
  '0100011111100010',
  '0100100000010010',
  '0111111111111110',
  '0000000000000000',
]

/** 패턴의 열 · 행 수. 행 길이가 다르면 가장 긴 행을 쓴다. */
export function patternSize(pattern: DotPattern): { columns: number; rows: number } {
  return {
    columns: pattern.reduce((widest, row) => Math.max(widest, row.length), 0),
    rows: pattern.length,
  }
}
